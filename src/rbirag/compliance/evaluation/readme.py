"""The compliance results section of the README, generated from the recorded runs.

Like the RAG results section, nothing in it is typed by hand: ``rbirag comply eval
readme`` rebuilds it between the ``COMPLIANCE:START`` / ``COMPLIANCE:END`` markers from
``results/compliance/runs`` (predictions, models, commits) and ``retrieval.json``. The
locked test split is shown only once every test clause has a prediction; until then the
section says how far the run has got.
"""

from __future__ import annotations

import json
import re
from collections.abc import Mapping
from pathlib import Path
from typing import Literal

from rbirag.compliance.evaluation.dataset import Dataset, dataset_stats
from rbirag.compliance.evaluation.metrics import (
    FAILURE_TYPES,
    ItemScore,
    Report,
    score_predictions,
    summarize,
)
from rbirag.compliance.evaluation.report import _fmt, paired_table, per_class_table
from rbirag.compliance.evaluation.run import load_predictions
from rbirag.compliance.evaluation.runs import RunRecord, load_runs

START = "<!-- COMPLIANCE:START (generated by `rbirag comply eval readme`) -->"
END = "<!-- COMPLIANCE:END -->"
_BLOCK = re.compile(r"<!-- COMPLIANCE:START.*?-->.*?<!-- COMPLIANCE:END -->", re.DOTALL)

ROWS: tuple[tuple[str, str, int], ...] = (
    ("verdict accuracy", "verdict_accuracy", 3),
    ("macro-F1", "macro_f1", 3),
    ("citation precision", "citation_precision", 3),
    ("citation recall", "citation_recall", 3),
    ("tool-argument validity", "tool_argument_validity", 3),
    ("tool-selection accuracy", "tool_selection_accuracy", 3),
    ("task success", "task_success", 3),
    ("calibration error (ECE, lower is better)", "ece", 3),
    ("tool steps / clause", "avg_steps", 1),
    ("LLM calls / clause", "avg_llm_calls", 1),
    ("tokens / clause", "tokens_per_clause", 0),
    ("latency s / clause", "latency_ms_per_clause", 1),
)

FAILURE_HELP: dict[str, str] = {
    "run_error": "the clause did not run (provider error)",
    "unsupported_verdict": "a verdict where the corpus cannot settle the clause",
    "over_abstention": "abstained although the corpus settles the clause",
    "scope_error": "not applicable confused with an applicable verdict",
    "wrong_entity": "relied on another entity type's Directions",
    "outdated_rule_missed": "accepted a clause that follows a replaced rule",
    "missed_issue": "called a conflict or gap compliant",
    "false_alarm": "called a compliant clause a conflict or gap",
    "conflict_gap_confusion": "conflict and gap swapped",
    "citation_miss": "right verdict, a required notification not cited",
    "invalid_tool_call": "right answer, but an invalid tool call on the way",
    "step_budget": "right answer, but over the step budget",
}


class SplitResult:
    def __init__(self, split: str, runs: list[RunRecord], items: int) -> None:
        self.split = split
        self.runs = runs
        self.items = items
        self.scored: dict[str, list[ItemScore]] = {}
        self.reports: dict[str, Report] = {}
        self.done: dict[str, int] = {}
        self.served: dict[str, list[str]] = {}

    @property
    def complete(self) -> bool:
        systems = {r.system for r in self.runs}
        return {"agent", "baseline"} <= systems and all(
            self.done.get(s, 0) >= self.items for s in systems
        )


def _split_result(
    dataset: Dataset,
    split: Literal["dev", "test"],
    runs_dir: Path,
    titles: Mapping[str, str] | None,
    backend: str | None,
) -> SplitResult:
    items = dataset.items(split)
    runs = [r for r in load_runs(runs_dir, split=split) if backend in (None, r.backend)]
    result = SplitResult(split, runs, len(items))
    for run in runs:
        preds = load_predictions(Path(run.predictions))
        preds = {k: v for k, v in preds.items() if k in {i.item_id for i in items}}
        result.done[run.system] = len(preds)
        result.served[run.system] = sorted({p.model for p in preds.values() if p.model})
        if preds:
            scores = score_predictions(items, preds, titles=titles)
            result.scored[run.system] = scores
            result.reports[run.system] = summarize(scores, system=run.system, split=split)
    return result


def _metric(report: Report, attr: str, digits: int) -> str:
    est = getattr(report, attr)
    if est is not None and attr.startswith("latency"):
        est = est.model_copy(
            update={"mean": est.mean / 1000, "low": est.low / 1000, "high": est.high / 1000}
        )
    return _fmt(est, digits)


def metrics_table(reports: Mapping[str, Report]) -> str:
    systems = [s for s in ("agent", "baseline") if s in reports]
    names = {"agent": "agent", "baseline": "fixed pipeline (baseline)"}
    lines = [
        "| metric | " + " | ".join(names[s] for s in systems) + " |",
        "|---|" + "---|" * len(systems),
    ]
    for label, attr, digits in ROWS:
        cells = [_metric(reports[s], attr, digits) for s in systems]
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def failures_table(reports: Mapping[str, Report]) -> str:
    systems = [s for s in ("agent", "baseline") if s in reports]
    used = [f for f in FAILURE_TYPES if any(reports[s].failures.get(f) for s in systems)]
    if not used:
        return "_No failures._"
    lines = [
        "| failure type | meaning | " + " | ".join(systems) + " |",
        "|---|---|" + "---|" * len(systems),
    ]
    for f in used:
        cells = [str(reports[s].failures.get(f, 0)) for s in systems]
        lines.append(f"| `{f}` | {FAILURE_HELP.get(f, '')} | " + " | ".join(cells) + " |")
    n = max(reports[s].n for s in systems)
    lines.append(
        "| **clauses without a failure** | | "
        + " | ".join(str(n - sum(reports[s].failures.values())) for s in systems)
        + " |"
    )
    return "\n".join(lines)


def retrieval_rows(path: Path) -> str:
    if not path.exists():
        return "_No retrieval results recorded._"
    rows = json.loads(path.read_text(encoding="utf-8"))
    by: dict[tuple[str, str], dict[str, object]] = {(r["split"], r["config"]): r for r in rows}
    configs = [
        ("fixed / bm25 / no filter", "BM25, no entity filter"),
        ("fixed / bm25 / entity filter", "**BM25 + entity filter (used)**"),
        ("fixed / hybrid / entity filter", "hybrid (BM25 + bge-small, RRF) + filter"),
        ("fixed / hybrid_rerank / entity filter", "hybrid + cross-encoder rerank + filter"),
        ("section / bm25 / entity filter", "section chunks, BM25 + filter"),
    ]
    lines = [
        "| retrieval (clause text as the query) | dev R@5 | dev MRR | test R@5 | test MRR "
        "| p50 ms |",
        "|---|---|---|---|---|---|",
    ]
    for key, label in configs:
        dev, test = by.get(("dev", key)), by.get(("test", key))
        if dev is None or test is None:
            continue
        lines.append(
            f"| {label} | {_r5(dev)} | {float(str(dev['mrr'])):.2f} | {_r5(test)} | "
            f"{float(str(test['mrr'])):.2f} | {float(str(test['p50_ms'])):,.0f} |"
        )
    return "\n".join(lines)


def _r5(row: Mapping[str, object]) -> str:
    recall = row["recall"]
    assert isinstance(recall, dict)
    return f"{float(recall['R@5']['mean']):.2f}"


def _runs_line(result: SplitResult) -> str:
    parts = []
    for r in sorted(result.runs, key=lambda x: x.system):
        served = ", ".join(f"`{m}`" for m in result.served.get(r.system, [])) or f"`{r.model}`"
        parts.append(
            f"{r.system}: {served} via {r.backend}, commit `{(r.commit or '?')[:7]}`, "
            f"{r.generated_at[:10]}"
        )
    return "; ".join(parts)


def readme_section(
    dataset: Dataset,
    *,
    runs_dir: Path,
    retrieval_path: Path,
    titles: Mapping[str, str] | None = None,
    backend: str | None = None,
) -> str:
    stats = dataset_stats(dataset)
    by_split = stats["by_split"]
    assert isinstance(by_split, dict)
    n_dev, n_test = sum(by_split["dev"].values()), sum(by_split["test"].values())
    dev = _split_result(dataset, "dev", runs_dir, titles, backend)
    test = _split_result(dataset, "test", runs_dir, titles, backend)
    out = [
        START,
        f"**Labelled set:** {stats['items']} synthetic policy clauses in {stats['policies']} "
        f"policies ({n_dev} dev / {n_test} test, split by policy), written by an AI from real "
        f"notifications with every evidence quote machine-checked against the corpus; "
        f"**{stats['human_verified']} human-verified**. Cost of every run: $0 (free tiers).",
        "",
    ]
    if test.complete:
        out += [
            f"**Test split (locked, n = {test.items}):** {_runs_line(test)}. 95% bootstrap CIs.",
            "",
            metrics_table(test.reports),
            "",
            "Agent minus baseline on the same clauses (paired bootstrap):",
            "",
            paired_table(test.scored, agent_key="agent", baseline_key="baseline"),
            "",
            "F1 per verdict (test):",
            "",
            per_class_table([test.reports["agent"], test.reports["baseline"]]),
            "",
        ]
    else:
        progress = ", ".join(
            f"{s} {test.done.get(s, 0)}/{test.items}" for s in ("agent", "baseline")
        )
        out += [
            f"**Test split (locked, n = {test.items}): in progress** ({progress} clauses). The run "
            "resumes each day within the free-tier quota with the code frozen; its numbers "
            "replace this note when every test clause has a prediction. Until then the dev "
            "numbers below are the only results, and they were used for iteration.",
            "",
        ]
    if dev.reports:
        out += [
            f"**Dev split (n = {dev.items}; used to iterate on prompts and to choose the "
            f"abstention threshold):** {_runs_line(dev)}. 95% bootstrap CIs.",
            "",
            metrics_table(dev.reports),
            "",
        ]
        if {"agent", "baseline"} <= set(dev.scored):
            out += [
                "Agent minus baseline on dev (paired bootstrap):",
                "",
                paired_table(dev.scored, agent_key="agent", baseline_key="baseline"),
                "",
            ]
    shown = test if test.complete else dev
    out += [
        f"Failures by type ({shown.split} split; each failing clause counted once, under its "
        "most important failure):",
        "",
        failures_table(shown.reports),
        "",
        retrieval_rows(retrieval_path),
        "",
        "Full reports: [`results/compliance/`](results/compliance/) (`results-dev.md`, "
        "`results-test.md`, predictions with every tool call, run records).",
        END,
    ]
    return "\n".join(out)


def update_readme(readme: Path, section: str) -> bool:
    """Replace the generated block; returns whether the file changed."""
    text = readme.read_text(encoding="utf-8")
    if not _BLOCK.search(text):
        raise ValueError(f"no {START!r} ... {END!r} block in {readme}")
    new = _BLOCK.sub(lambda _: section, text, count=1)
    if new == text:
        return False
    readme.write_text(new, encoding="utf-8")
    return True
